def main():
    target = Path(__file__).resolve().parents[1] / 'data' / 'examples.csv'
    target.parent.mkdir(exist_ok=True)
    rows = []
    for category, content in CORPUS.items():
        for i, line in enumerate(content.splitlines(), 1):
            title, description = line.split('|')
            group = f'{category}-{i:02}'
            if category == 'study' and i == 25: group = 'study-01'
            rows.append([f'{category}-{i:03}', title, description, category, 'AI辅助逐条编写的课程示例；非真实用户数据', group])
    with target.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['id', 'title', 'description', 'category', 'source', 'group_id'])
        writer.writerows(rows)
    print(f'Wrote {len(rows)} illustrative rows to {target}')

if __name__ == '__main__': main()
